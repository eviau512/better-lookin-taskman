inline LangMode GetEffectiveLang(LangMode mode) {
    if (mode != LangMode::Auto) return mode;
    LANGID lang = GetUserDefaultUILanguage();
    WORD prim = PRIMARYLANGID(lang);
    WORD sub = SUBLANGID(lang);
    if (prim == LANG_CHINESE) {
        if (sub == SUBLANG_CHINESE_TRADITIONAL || sub == SUBLANG_CHINESE_HONGKONG || sub == SUBLANG_CHINESE_MACAU) {
            return LangMode::TraditionalChinese;
        }
        return LangMode::Chinese;
    }
    if (prim == LANG_JAPANESE) return LangMode::Japanese;
    if (prim == LANG_KOREAN)   return LangMode::Korean;
    if (prim == LANG_GERMAN)   return LangMode::German;
    if (prim == LANG_FRENCH)   return LangMode::French;
    if (prim == LANG_SPANISH)  return LangMode::Spanish;
    if (prim == LANG_RUSSIAN)  return LangMode::Russian;
    return LangMode::English;
}

